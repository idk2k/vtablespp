#include <iostream>

// =========================================================================================
// OBJECT MEMORY LAYOUT (MSVC x64 alignment)
// 
// [Derived object inside main()]
// Offset 0x00: [ vptr for Left  ] ---> Points to Derived::vftable{for Left} (Primary)
// Offset 0x08: [ vptr for Right ] ---> Points to Derived::vftable{for Right} (Secondary)
// Size: 16 bytes (0x10)
// =========================================================================================

struct Left {
    virtual void print() const { std::cout << "Left\n"; }
};

struct Right {
    virtual void print() const { std::cout << "Right\n"; }
};

struct Derived : Left, Right {
    // Shared Implementation: 
    // This is the single, concrete function body for both interfaces.
    // MSVC binds it to the primary layout (+0). Thus, this raw function NATIVELY 
    // expects RCX (the 'this' pointer) to point to the exact start of 'Derived'.
    void print() const override {
        std::cout << "Derived\n";
    }
};

int main() {
    Derived object{};

    // ---------------------------------------------------------------------------------
    // CASE 1: Polymorphic Call via Secondary Interface Pointer (Triggers THIS Thunk)
    // ---------------------------------------------------------------------------------
    Right* r = &object; // Pointer is shifted by +8 bytes to point to Right's sub-object.

    // Dynamic Binding: The compiler only knows 'r' is a 'Right*'.
    // 
    // Assembly generated by compiler:
    // 1. Fetch vptr from 'r' (which points to Derived::vftable{for Right})
    // 2. Call Slot 0 (Index 0) of that table.
    // 
    // COMPILER BEHIND THE SCENES (The This Adjustment Thunk):
    // Inside 'Derived::vftable{for Right}', Slot 0 contains the address of a Thunk.
    // Before reaching the raw Derived::print(), execution goes through this code:
    //
    // [Bytecode: 48 83 E9 08] -> sub rcx, 8          ; ADJUSTMENT: Shift Right* back to Derived*
    // [Bytecode: E9 XX XX XX] -> jmp Derived::print  ; Jump directly to the raw function
    // 
    // Result: RCX is perfectly aligned to the start of Derived, and the function executes safely.
    r->print();

    // ---------------------------------------------------------------------------------
    // CASE 2: Call via Concrete Class Pointer (Bypasses THIS Thunk)
    // ---------------------------------------------------------------------------------
    Derived* d = &object; // Points directly to the start of the object (Offset 0x00).

    // Static Type Knowledge: The compiler explicitly knows 'd' is a 'Derived*'.
    // 
    // Assembly generated by compiler:
    // 1. Fetch vptr from 'd' (uses Left/Primary vtable).
    // 2. Calls Slot 0 directly (which points straight to the raw Derived::print() body).
    // 
    // NO Thunk is used here. No 'sub rcx, 8' is executed, because the pointer in 'd' 
    // already perfectly matches what the raw function expects.
    d->print();

    return 0;
}
