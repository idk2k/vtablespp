#include <iostream>

// =========================================================================================
// MEMORY LAYOUT OF THE OBJECTS (MSVC x64 alignment)
// 
// [Derived object in memory]
// Offset 0x00: [ vptr for Left  ] ---> Points to Derived::vftable{for Left}
// Offset 0x08: [ vptr for Right ] ---> Points to Derived::vftable{for Right}
// Offset 0x10: [ int x (20)     ] ---> Member data
// Size: 24 bytes (0x18)
// =========================================================================================

struct Left {
    virtual void left() const {
        std::cout << (void*)this << std::endl;
    }
};

struct Right {
    // Contract: This interface expects its virtual clone() to return a 'Right*' pointer.
    virtual Right* clone() const {
        return new Right{ *this };
    }
};

struct Derived : Left, Right {
    void left() const override {
        std::cout << (void*)this << std::endl;
    }

    // Covariant Return Type: Derived overrides clone() and changes the return type to 'Derived*'.
    // 
    // COMPILER BEHIND THE SCENES (The Two-Slot VFTABLE for Right):
    // Inside 'Derived::vftable{for Right}', MSVC allocates two slots:
    // Slot 0 (Index 0): [ Right * Derived::clone() ] -> Points to the RETURN ADJUSTMENT THUNK
    // Slot 1 (Index 1): [ Derived * Derived::clone() ] -> Points to this actual function body below
    Derived* clone() const override {
        return new Derived{ *this };
    }

    int x{ 20 };
};

int main() {
    Derived object{};

    // ---------------------------------------------------------------------------------
    // CASE 1: Polymorphic Call via Interface Pointer (Triggers Thunk)
    // ---------------------------------------------------------------------------------
    Right* r = &object; // Pointer shifted by +8 bytes to point to Right's sub-object.

    // Dynamic Binding: The compiler only knows 'r' is a 'Right*'. 
    // It enforces the 'Right' interface contract, which expects a 'Right*' back.
    // 
    // Assembly generated by compiler:
    // 1. Fetch vptr from 'r'
    // 2. Call Slot 0 (Index 0) -> Jumps to the Return Adjustment Thunk!
    // 
    // What the Thunk does (Pseudo-bytecode execution):
    //   call  Derived::clone()         ; Calls Slot 1, returns a raw 'Derived*' in RAX
    //   cmp   rax, 0                   ; Safety check for nullptr
    //   je    skip_adjustment          ; [Opcode: 74 XX]
    //   add   rax, 8                   ; [Opcode: 48 83 C0 08] <- THE RETURN ADJUSTMENT!
    //                                  ; Shifts 'Derived*' to 'Right*' to satisfy the caller.
    // skip_adjustment:
    //   ret
    Right* p = r->clone();

    // ---------------------------------------------------------------------------------
    // CASE 2: Call via Concrete Class Pointer (Bypasses Thunk)
    // ---------------------------------------------------------------------------------
    Derived* d = &object; // Points directly to the start of the object (Offset 0x00).

    // Static Type Knowledge: The compiler explicitly knows 'd' is a 'Derived*'.
    // The caller expects a 'Derived*' back, which matches the raw return type of the function.
    // 
    // Assembly generated by compiler:
    // 1. Fetch vptr from 'd' (uses Left/Primary vtable)
    // 2. Calls Slot 1 (Index 1) directly OR resolves the address statically (Devirtualization).
    // NO Thunk is used here. No 'add rax, 8' is executed.
    Derived* p2 = d->clone();

    delete p;
    delete p2;

    return 0;
}
